const dictionaries = { zh, en };

let currentLanguage = "zh";

export function setLanguage(language) {
  currentLanguage = dictionaries[language] ? language : "zh";
}

export function getLanguage() {
  return currentLanguage;
}

/** Pick a language from an explicit setting, otherwise the system locale. */
export function resolveLanguage(setting) {
  if (setting === "zh" || setting === "en") return setting;
  const preferred = (navigator.language || "zh").toLowerCase();
  return preferred.startsWith("zh") ? "zh" : "en";
}

/**
 * Translate a key. Values may be functions for pluralisation/formatting.
 * Unknown keys fall back to the raw key so gaps are obvious, not silent.
 */
export function t(key, ...args) {
  const dictionary = dictionaries[currentLanguage] || zh;
  const value = dictionary[key] ?? zh[key];
  if (value === undefined) return key;
  return typeof value === "function" ? value(...args) : value;
}
