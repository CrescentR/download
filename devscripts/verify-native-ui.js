  const rect = selector => document.querySelector(selector).getBoundingClientRect();
  check(rect('.window-titlebar').height===36,'Titlebar must be 36px');
  check(rect('.sidebar').width===208,'Sidebar must be 208px');
  check(rect('.statusbar').height===32,'Statusbar must be 32px');
  check(document.fonts.check('12px "JetBrains Mono"'),'Local mono font must load');
  check(getComputedStyle(document.querySelector('.task-bar')).height==='4px','Progress must be 4px');
