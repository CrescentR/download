  click('[data-action="task-filter"][data-value="all"]');await wait();
  check(document.querySelectorAll('.task').length===3,'Filtering preserves tasks');
  click('[data-action="toggle-lang"]');await wait();check(document.querySelector('[data-action="analyze"]').textContent.includes('Analyze'),'Language switch');
