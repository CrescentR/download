  subtitle.checked=true;subtitle.dispatchEvent(new Event('change',{bubbles:true}));await wait();
  check(document.querySelector('[data-parser-option="embedSubtitles"]').checked,'Subtitle selection persists');
  click('[data-action="dismiss-preview"]');await wait();check(!document.querySelector('.parser-dialog'),'Modal close');
