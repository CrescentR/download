  click('[data-action="analyze"]'); await wait();await wait();
  check(document.querySelector('.parser-dialog'),'Parser is a modal');
  check(document.querySelector('[data-action="select-format"][aria-pressed="true"]')?.textContent.includes('Audio'),'FLAC preset selects audio');
